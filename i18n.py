def detect_language():
    """Best guess of the OS UI language, falling back to English."""
    name = ""
    try:
        if sys.platform == "win32":
            import ctypes
            name = locale.windows_locale.get(ctypes.windll.kernel32.GetUserDefaultUILanguage(), "")
        elif sys.platform == "darwin":
            name = subprocess.run(["defaults", "read", "-g", "AppleLocale"], capture_output=True,
                                  text=True, timeout=2).stdout.strip()
        if not name:
            name = (os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or os.environ.get("LANG")
                    or locale.getlocale()[0] or "")
    except Exception:
        pass
    code = name[:2].lower()
    return code if code in LANGS else "en"
